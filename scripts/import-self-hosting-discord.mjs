import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'C:/Users/ferdi/Desktop/Sylo/docs/self-hosting.md';
const DEST = 'C:/Users/ferdi/Desktop/sylo-docs/src/content/docs/self-hosting/discord.md';

let body = readFileSync(SRC, 'utf8').split('\n').slice(1).join('\n').replace(/^\n+/, '');

// Drop the manual anchor-link TOC — Starlight renders its own "On this page"
// sidebar from the headings, so a second hand-written one right at the top
// is redundant clutter here (it earns its keep in the plain GitHub README).
const tocStart = body.indexOf('- [Quick start]');
const headingStart = body.indexOf('## Quick start');
if (tocStart === -1 || headingStart === -1 || headingStart < tocStart) {
  throw new Error('TOC block not found — check the source file');
}
body = body.slice(0, tocStart) + body.slice(headingStart);

// modules/README.md doesn't exist on this site (module pages are
// autogenerated); point at the first module page instead.
body = body.replace('[`docs/modules/`](modules/README.md)', '[the module docs](/modules/moderation/)');
// postgres.md isn't imported here (advanced/hosted-scale topic) — link out
// to the source file on GitHub instead of a dead relative link.
body = body.replaceAll(
  '[docs/postgres.md](postgres.md)',
  '[docs/postgres.md](https://github.com/Ferdinand99/Sylo/blob/main/docs/postgres.md)'
);
body = body.replace(
  '[docs/postgres.md](postgres.md#backups-and-restore-on-postgres)',
  '[docs/postgres.md](https://github.com/Ferdinand99/Sylo/blob/main/docs/postgres.md#backups-and-restore-on-postgres)'
);

const frontmatter = [
  '---',
  'title: Self-host on Discord',
  'description: Install, configure, reverse-proxy, back up and upgrade a self-hosted Sylo Discord bot.',
  '---',
  '',
].join('\n');

writeFileSync(DEST, frontmatter + '\n' + body);
console.log('wrote', DEST);
